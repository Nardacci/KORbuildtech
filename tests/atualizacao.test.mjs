/* KORbuild — aviso de atualização do app (js/atualizacao.js) e versão na tela de entrada. Uso: python3 -m http.server 8123 &  →  node tests/atualizacao.test.mjs [http://localhost:8123/] */
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const BASE = (process.argv.slice(2).find((a) => a.startsWith('http')) || 'http://localhost:8123/').replace(/\/?$/, '/');
let falhas = 0;
const verificar = (c, t, d) => { if (c) console.log('  ok  ' + t); else { falhas++; console.log('FALHA ' + t + (d !== undefined ? '\n      encontrado: ' + JSON.stringify(d) : '')); } };
const sw = readFileSync(new URL('../sw.js', import.meta.url), 'utf8'), cfg = readFileSync(new URL('../js/config.js', import.meta.url), 'utf8');
const cache = sw.match(/CACHE = 'korbuild-(v\d+)'/)[1], versao = cfg.match(/VERSAO_APP = '(v\d+)'/)[1];
verificar(cache === versao, 'a versão da tela (config.js) é a mesma do cache do service worker (' + cache + ')', [cache, versao]);
verificar(/'js\/atualizacao\.js'/.test(sw), 'o aviso de atualização está na lista de arquivos guardados no aparelho');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
await ctx.addInitScript(() => { try { localStorage.setItem('kbt.idioma', 'pt'); } catch { /* */ } });
await ctx.route(/fonts\.|tile\.openstreetmap|open-meteo|supabase\.co/, (r) => r.abort());
const p = await ctx.newPage(); const erros = []; p.on('pageerror', (e) => erros.push(e.message));
await p.goto(BASE + '#/entrar'); await p.waitForSelector('#form-login-oficial', { timeout: 30000 });
verificar((await p.locator('.versao-app').innerText()).includes(versao), 'a tela de entrar mostra a versão do app', await p.locator('.versao-app').innerText());
const m = (n, ...a) => p.evaluate(async ([n, a]) => { const mod = await import('./js/atualizacao.js'); mod[n](...(a.map((x) => (x === 'FN' ? () => { window.__recarregou = true; } : x)))); }, [n, a]);
await m('avisarBaixando');
verificar((await p.locator('#aviso-atualizacao').innerText()).includes('Baixando a versão nova'), 'mostra "Baixando a versão nova"');
await m('avisarAtualizando');
verificar((await p.locator('#aviso-atualizacao').innerText()).includes('Atualizando o app'), 'mostra "Atualizando o app"');
verificar(await p.locator('#aviso-atualizacao').count() === 1, 'é uma faixa só (não empilha)');
const topo = await p.locator('#aviso-atualizacao').boundingBox();
verificar(topo && topo.y === 0 && topo.width >= 380, 'a faixa fica fixa no topo, na largura do celular', topo);
await m('avisarPronta', 'FN');
await p.click('#atualizar-agora');
verificar(await p.evaluate(() => window.__recarregou === true), 'com algo em edição: o botão "Atualizar agora" recarrega quando a pessoa toca');
await m('esconderAviso');
verificar(await p.locator('#aviso-atualizacao').count() === 0, 'o aviso some');
verificar(erros.length === 0, 'sem erros de JavaScript', erros);
await browser.close();
console.log(falhas ? '\n' + falhas + ' falha(s).' : '\nTudo certo.');
process.exit(falhas ? 1 : 0);
